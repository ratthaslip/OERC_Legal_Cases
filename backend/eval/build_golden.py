def build() -> list[dict]:
    out = []
    for i, (cat, q, ans, src, ev, opt) in enumerate(Q, 1):
        out.append({"id": f"G{i:02d}", "category": cat, "question": q, "reference_answer": ans,
                    "expected_sources": src, "evidence": ev, "user": opt.get("user", "lgl1"),
                    "as_of": opt.get("as_of"), "expected_status": opt.get("expected_status", "ANSWERED"),
                    "must_not_cite": opt.get("must_not_cite", []), "must_not_kinds": opt.get("must_not_kinds", []),
                    "expected_title_contains": opt.get("expected_title_contains"),
                    "must_include": opt.get("must_include", []), "require_all": opt.get("require_all", False),
                    "data": opt.get("data", "law")})
    return out


def check(items: list[dict]) -> list[str]:
    """หลักฐานทุกข้อความต้องมีอยู่ในตัวบท (รุ่นล่าสุดของ ELI นั้น) — กันคำตอบอ้างอิงผิด"""
    laws, instruments = {}, set()
    for f in (Path(__file__).parents[1] / "app" / "seed" / "laws").glob("*.json"):
        for inst in json.loads(f.read_text(encoding="utf-8")):
            instruments.add(inst["id"])
            for p in inst["provisions"]:
                laws[p["id"]] = p["versions"]
    errs = []
    for it in items:
        for eli in it["expected_sources"] + it["must_not_cite"]:
            if eli not in laws and eli not in instruments:
                errs.append(f"{it['id']}: ไม่มีตัวบท {eli}")
        for eli, phrases in it["evidence"].items():
            text = " ".join(v["text"] for v in laws.get(eli, []))
            for ph in phrases:
                if ph not in text:
                    errs.append(f"{it['id']}: ไม่พบหลักฐาน '{ph}' ใน {eli}")
    return errs


if __name__ == "__main__":
    items = build()
    errs = check(items)
    path = Path(__file__).with_name("golden_set.json")
    path.write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(items)} ข้อ → {path}")
    print("\n".join(errs) if errs else "หลักฐานทุกข้อพบในตัวบทจริง")
